%% build_hpt_switching_model.m
% Build a switching-level Specialized Power Systems HPT model.
%
% Scope:
%   - Main power path: 10 kV source -> series injection transformer ->
%     10 kV/400 V line-frequency transformer -> 400 V load
%   - Energy-extraction converter: shunt VSC at the 400 V bus, maintaining DC link
%   - Regulation converter: three single-phase H-bridges injecting series voltage
%   - Shared DC-link capacitor, L/R shunt filters, three-phase AC fault
%   - Measurement/logging outputs for verification

clear; clc;
run('parameters.m');

MODEL = 'hpt_switching_model';

if bdIsLoaded(MODEL)
    close_system(MODEL, 0);
end
if exist([MODEL '.slx'], 'file')
    delete([MODEL '.slx']);
end

