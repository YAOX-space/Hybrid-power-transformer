function connect_port(model, src_blk, src_kind, src_idx, dst_blk, dst_kind, dst_idx)
    src = get_param([model '/' src_blk], 'PortHandles');
    dst = get_param([model '/' dst_blk], 'PortHandles');
    add_line(model, src.(src_kind)(src_idx), dst.(dst_kind)(dst_idx), 'autorouting', 'on');
end

function add_signal_goto(model, name, tag, x, y)
    add_block('simulink/Signal Routing/Goto', [model '/' name], ...
        'GotoTag', tag, ...
        'TagVisibility', 'local', ...
        'ShowName', 'off', ...
        'Position', [x y x+55 y+18]);
end

function add_signal_from(model, name, tag, x, y)
    add_block('simulink/Signal Routing/From', [model '/' name], ...
        'GotoTag', tag, ...
        'ShowName', 'off', ...
        'Position', [x y x+55 y+18]);
end

function add_controller_inputs(model, target, x, y)
    tags = {'hpt_clk','hpt_sc_id','hpt_t_fault','hpt_variant','hpt_fault_mag', ...
            'hpt_vdc','hpt_v2abc','hpt_i2abc','hpt_ctrl_mode', ...
            'hpt_rl_energy_bias','hpt_rl_reg_bias','hpt_rl_current_bias', ...
            'hpt_vdc_ref_delta','hpt_v2_ref_delta','hpt_ilim_delta','hpt_fahc_strategy'};
    names = {'Clock','ScId','TFault','FaultVariant','FaultMag', ...
             'Vdc','V2abc','I2abc','ControllerMode', ...
             'RLEnergyBias','RLRegBias','RLCurrentBias', ...
             'VDCRefDelta','V2RefDelta','ILimDelta','FAHCStrategy'};
    for k = 1:numel(tags)
        add_signal_from(model, ['From_' names{k} '_' target], tags{k}, x, y + 25*(k-1));
    end
end
