    'vq_lv = -alpha*st + beta*ct;', ...
    'id_e = (ialpha*ct + ibeta*st) / max(i_base_peak, 1);', ...
    'iq_e = (-ialpha*st + ibeta*ct) / max(i_base_peak, 1);', ...
    'reg_mag_prev = sqrt(last_act(1)*last_act(1) + last_act(2)*last_act(2));', ...
    'energy_mag_prev = sqrt(last_act(3)*last_act(3) + last_act(4)*last_act(4));', ...
    'fault_entry = double((g_vpos < 0.92) || (g_vpos > 1.10) || (g_vneg > 0.06));', ...
    'normal_band = double((g_vpos >= 0.90) && (g_vpos <= 1.10) && (g_vneg <= 0.06));', ...
    'recovery_reentry_fault = double((g_vpos < 0.86) || (g_vpos > 1.22) || (g_vneg > 0.12));', ...
    'if t_clock < gridnorm_startup_s', ...
    '    fault_entry = 0;', ...
