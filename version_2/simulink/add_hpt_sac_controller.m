function add_hpt_sac_controller(M, x, y)
% add_hpt_sac_controller adds the topology-neutral HPT SAC command subsystem.
%
% Outputs:
%   port 1: six regulating H-bridge modulation references
%   port 2: three energy-bridge modulation references
%   port 3: 24-D observation vector
%   port 4: 4-D action vector
%           [m_reg_d, m_reg_q, m_energy_d, m_energy_q]

P = @(a, b, w, h) [a b a+w b+h];
S = [M '/HPTSACController'];
add_block('built-in/Subsystem', S, 'Position', P(x, y, 240, 165));
set_param(S, 'ShowName', 'on');
open_system(S);

add_block('simulink/Sources/In1', [S '/Vlv'], 'Position', P(35, 35, 30, 18));
add_block('simulink/Sources/In1', [S '/Vdc'], 'Position', P(35, 70, 30, 18));
add_block('simulink/Sources/In1', [S '/Venergy'], 'Position', P(35, 105, 30, 18));
add_block('simulink/Sources/In1', [S '/Ienergy'], 'Position', P(35, 140, 30, 18));
add_block('simulink/Sources/In1', [S '/Vgrid'], 'Position', P(35, 175, 30, 18));

ctrl = [S '/HPT_SAC_HLC'];
add_block('simulink/User-Defined Functions/MATLAB Function', ctrl, ...
    'Position', P(125, 38, 210, 120));
set_hpt_sac_matlab_function_code(ctrl, hpt_sac_hlc_code());

paramNames = {'Ts', 'GridF0', 'VrefPhase', 'GridVrefPhase', 'VdcRef', 'PolicyMode', ...
    'ActorSelectMode', 'ActorFilterTau', 'RegMax', 'EnergyMax', 'IBasePeak', 'InjPhase', 'RegPolarity', ...
    'RegDGain', 'RegQGain', 'DynamicRegLimit', 'EnergyPolarity', ...
    'TopologyId', 'FixedRegD', 'FixedRegQ', 'FixedEnergyD', 'FixedEnergyQ', ...
    'GuardEnable', 'EnergyIdMax', 'EnergyCurrentKp', 'EnergyCurrentKi', ...
    'EnergyVffGain', 'EnergyControlSign', 'ConventionalRegScale', ...
    'ConventionalEnergyScale', 'ConventionalRegScaleSag', ...
    'ConventionalRegScaleSwell', 'ConventionalEnergyScaleSag', ...
    'ConventionalEnergyScaleSwell', 'ConventionalRecoveryRegGain', ...
    'ConventionalRecoveryRegMax', 'ConventionalRecoveryHoldS', ...
    'ConventionalVRegKp', 'ConventionalVRegKi', 'ConventionalVdcKp', ...
    'ConventionalVdcKi', 'GridNormStartupS', 'FaultTimeNormS', ...
    'RecoveryTimeNormS', 'PhaseOverrideEnable', 'PhaseFaultStartS', ...
    'PhaseFaultClearS', 'PhaseRecoveryEndS', 'TrajT', 'TrajAction'};
paramValues = {'hpt_ctrl_Ts', 'hpt_grid_f0', 'hpt_sac_vref_phase', ...
    'hpt_sac_grid_vref_phase', 'hpt_sac_vdc_ref', 'hpt_sac_policy_mode', 'hpt_sac_actor_select_mode', 'hpt_sac_actor_filter_tau', ...
    'hpt_sac_reg_max', 'hpt_sac_energy_max', 'hpt_sac_i_base_peak', 'hpt_inj_phase_offset', ...
    'hpt_sac_reg_polarity', 'hpt_sac_reg_d_gain', 'hpt_sac_reg_q_gain', ...
    'hpt_sac_dynamic_reg_limit', 'hpt_energy_bridge_polarity', 'hpt_sac_topology_id', 'hpt_sac_fixed_reg_d', ...
    'hpt_sac_fixed_reg_q', 'hpt_sac_fixed_energy_d', 'hpt_sac_fixed_energy_q', ...
    'hpt_sac_guard_enable', 'hpt_energy_id_max', 'hpt_energy_i_kp', ...
    'hpt_energy_i_ki', 'hpt_energy_vff_gain', 'hpt_energy_control_sign', ...
    'hpt_conventional_reg_scale', 'hpt_conventional_energy_scale', ...
    'hpt_conventional_reg_scale_sag', 'hpt_conventional_reg_scale_swell', ...
    'hpt_conventional_energy_scale_sag', 'hpt_conventional_energy_scale_swell', ...
    'hpt_conventional_recovery_reg_gain', 'hpt_conventional_recovery_reg_max', ...
    'hpt_conventional_recovery_hold_s', 'hpt_vreg_kp', 'hpt_vreg_ki', ...
    'hpt_vdc_kp', 'hpt_vdc_ki', 'hpt_sac_gridnorm_startup_s', ...
    'hpt_sac_fault_time_norm_s', 'hpt_sac_recovery_time_norm_s', ...
    'hpt_sac_phase_override_enable', 'hpt_sac_phase_fault_start_s', ...
    'hpt_sac_phase_fault_clear_s', 'hpt_sac_phase_recovery_end_s', ...
    'hpt_traj_t', 'hpt_traj_action'};
for pidx = 1:numel(paramNames)
    add_block('simulink/Sources/Constant', [S '/' paramNames{pidx}], ...
        'Position', P(35, 220 + (pidx-1)*30, 70, 20), ...
        'Value', paramValues{pidx});
    add_line(S, [paramNames{pidx} '/1'], sprintf('HPT_SAC_HLC/%d', pidx+5), ...
        'autorouting', 'on');
end

add_block('simulink/Sinks/Out1', [S '/m_reg6'], 'Position', P(390, 45, 30, 18));
add_block('simulink/Sinks/Out1', [S '/m_energy3'], 'Position', P(390, 80, 30, 18));
add_block('simulink/Sinks/Out1', [S '/obs24'], 'Position', P(390, 115, 30, 18));
add_block('simulink/Sinks/Out1', [S '/act4'], 'Position', P(390, 150, 30, 18));

add_line(S, 'Vlv/1', 'HPT_SAC_HLC/1', 'autorouting', 'on');
add_line(S, 'Vdc/1', 'HPT_SAC_HLC/2', 'autorouting', 'on');
add_line(S, 'Venergy/1', 'HPT_SAC_HLC/3', 'autorouting', 'on');
add_line(S, 'Ienergy/1', 'HPT_SAC_HLC/4', 'autorouting', 'on');
add_line(S, 'Vgrid/1', 'HPT_SAC_HLC/5', 'autorouting', 'on');
add_line(S, 'HPT_SAC_HLC/1', 'm_reg6/1', 'autorouting', 'on');
add_line(S, 'HPT_SAC_HLC/2', 'm_energy3/1', 'autorouting', 'on');
add_line(S, 'HPT_SAC_HLC/3', 'obs24/1', 'autorouting', 'on');
add_line(S, 'HPT_SAC_HLC/4', 'act4/1', 'autorouting', 'on');
end

function set_hpt_sac_matlab_function_code(blockPath, codeText)
rt = sfroot;
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', blockPath);
chart.Script = codeText;
end

