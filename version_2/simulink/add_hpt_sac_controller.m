    '    scheduled_recovery = double((t_clock >= phase_fault_clear_s) && (t_clock < phase_recovery_end_s));', ...
    '    obs_sag = double(scheduled_fault >= 0.5 && g_vpos <= 1.0);', ...
    '    obs_swell = double(scheduled_fault >= 0.5 && g_vpos > 1.0);', ...
    '    obs_fault_active = scheduled_fault;', ...
    '    obs_recovery_active = scheduled_recovery;', ...
    '    obs_tfault = 0; if scheduled_fault >= 0.5; obs_tfault = min(max((t_clock - phase_fault_start_s)/max(fault_time_norm_s, ts), 0), 1); end', ...
